//! `ConfigurationKey.java` -> `docs/inventory/config-keys.csv` and
//! `crates/dhis-config/src/keys_generated.rs`.

use anyhow::{Context, Result, bail};

use crate::eval::Eval;
use crate::java::{Expr, JavaIndex};

pub const FQN: &str = "org.hisp.dhis.external.conf.ConfigurationKey";

pub const COLUMNS: &[&str] = &[
    "name",
    "key",
    "default_value",
    "default_is_null",
    "confidential",
    "aliases",
    "deprecated",
    "description",
];

#[derive(Debug, Clone)]
pub struct Key {
    pub name: String,
    pub key: String,
    pub default_value: Option<String>,
    pub confidential: bool,
    pub aliases: Vec<String>,
    pub deprecated: bool,
    pub description: String,
}

pub fn extract(idx: &JavaIndex) -> Result<Vec<Key>> {
    let t = idx.by_fqn(FQN).context("ConfigurationKey.java not found")?;
    let ev = Eval::new(idx);
    let mut out = Vec::new();
    for c in &t.enum_constants {
        let s = |e: &Expr| -> Result<Option<String>> {
            if matches!(e, Expr::Other(o) if o == "null") {
                return Ok(None);
            }
            ev.string(e, t, 0)
                .map(Some)
                .map_err(|u| anyhow::anyhow!("{}: cannot evaluate {}", c.name, u.0))
        };
        let (key, default_value, confidential, aliases) = match c.args.as_slice() {
            [k] => (s(k)?, None, false, vec![]),
            [k, d] => (s(k)?, s(d)?, false, vec![]),
            [k, d, conf] => (s(k)?, s(d)?, *conf == Expr::Bool(true), vec![]),
            [k, d, conf, al] => (
                s(k)?,
                s(d)?,
                *conf == Expr::Bool(true),
                ev.strings(al, t)
                    .map_err(|u| anyhow::anyhow!("{}: aliases {}", c.name, u.0))?,
            ),
            other => bail!("{}: unexpected constructor args {other:?}", c.name),
        };
        out.push(Key {
            name: c.name.clone(),
            key: key.with_context(|| format!("{}: null key", c.name))?,
            default_value,
            confidential,
            aliases,
            deprecated: c.annotations.iter().any(|a| a.name == "Deprecated"),
            description: c.doc.clone().unwrap_or_default(),
        });
    }
    if out.len() < 100 {
        bail!(
            "only {} configuration keys found; parser is probably broken",
            out.len()
        );
    }
    Ok(out)
}

pub fn record(k: &Key) -> Vec<String> {
    vec![
        k.name.clone(),
        k.key.clone(),
        k.default_value.clone().unwrap_or_default(),
        k.default_value.is_none().to_string(),
        k.confidential.to_string(),
        k.aliases.join(";"),
        k.deprecated.to_string(),
        k.description.clone(),
    ]
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

pub fn render_rust(keys: &[Key]) -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by tools/inventory from ConfigurationKey.java. Do not edit by hand.\n\
         // Regenerate with: cargo run -p dhis-inventory -- --java-root ../dhis2-core\n\n",
    );
    s.push_str(
        "/// `org.hisp.dhis.external.conf.ConfigurationKey`, constant names kept verbatim.\n\
         #[allow(non_camel_case_types)]\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n\
         pub enum ConfigurationKey {\n",
    );
    for k in keys {
        if k.deprecated {
            s.push_str("    #[deprecated]\n");
        }
        s.push_str(&format!("    {},\n", k.name));
    }
    s.push_str("}\n\n");
    s.push_str("#[allow(deprecated)]\npub static ALL_KEYS: &[ConfigurationKey] = &[\n");
    for k in keys {
        s.push_str(&format!("    ConfigurationKey::{},\n", k.name));
    }
    s.push_str("];\n\n");
    s.push_str("pub static KEY_DEFS: &[KeyDef] = &[\n");
    for k in keys {
        let default = match &k.default_value {
            Some(d) => format!("Some({})", lit(d)),
            None => "None".into(),
        };
        let aliases: Vec<String> = k.aliases.iter().map(|a| lit(a)).collect();
        s.push_str(&format!(
            "    KeyDef {{ name: {}, key: {}, default_value: {default}, confidential: {}, aliases: &[{}] }},\n",
            lit(&k.name),
            lit(&k.key),
            k.confidential,
            aliases.join(", ")
        ));
    }
    s.push_str("];\n");
    s
}
